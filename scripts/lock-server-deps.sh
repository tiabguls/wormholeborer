#!/usr/bin/env bash
# Pins the exact wheels a Debian 13 (CPython 3.13, glibc 2.41, x86_64) server installs, with hashes.
# A full multi-platform hash lock is ~48 KB, too large for Linode's 64 KB base64 user-data limit.
set -euo pipefail
cd "$(dirname "$0")/.."
pkg=src/wormholeborer
work=$(mktemp -d)
trap 'rm -r -- "$work"' EXIT
# pip does not expand a glibc version to older manylinux tags, so list them newest-first,
# which is the preference order pip uses on the server itself.
platforms=()
for minor in $(seq 41 -1 5); do platforms+=(--platform "manylinux_2_${minor}_x86_64"); done
platforms+=(--platform manylinux2014_x86_64 --platform manylinux2010_x86_64 --platform manylinux1_x86_64)
uvx pip download --quiet --only-binary=:all: "${platforms[@]}" \
  --python-version 3.13 --implementation cp -r "$pkg/server-requirements.in" -d "$work"
{
  echo "# Generated by scripts/lock-server-deps.sh from server-requirements.in. Do not edit."
  for f in "$work"/*.whl; do
    name=$(basename "$f" | cut -d- -f1 | tr '_' '-' | tr '[:upper:]' '[:lower:]')
    version=$(basename "$f" | cut -d- -f2)
    echo "$name==$version --hash=sha256:$(sha256sum "$f" | cut -d' ' -f1)"
  done
} >"$pkg/server-requirements.txt"
